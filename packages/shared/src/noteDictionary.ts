function buildDictionary(): Record<string, FlavorFamilyId> {
  const dict: Record<string, FlavorFamilyId> = {};
  for (const [family, words] of Object.entries(GROUPS) as [FlavorFamilyId, string[]][]) {
    for (const w of words) {
      const key = normalizeText(w);
      if (!(key in dict)) dict[key] = family;
    }
  }
  return dict;
}

/** Normalised note phrase → flavor family id. */
export const NOTE_DICTIONARY: Readonly<Record<string, FlavorFamilyId>> = buildDictionary();

const MAX_NGRAM = 4;

function singular(word: string): string {
  if (word.endsWith('ies') && word.length > 4) return `${word.slice(0, -3)}y`;
  if (/(ch|sh|x|ss)es$/.test(word)) return word.slice(0, -2);
  if (word.endsWith('oes') && word.length > 4) return word.slice(0, -2);
  if (word.endsWith('s') && !word.endsWith('ss') && word.length > 3) return word.slice(0, -1);
  return word;
}

function lookup(phrase: string): FlavorFamilyId | undefined {
  return NOTE_DICTIONARY[phrase] ?? NOTE_DICTIONARY[phrase.split(' ').map(singular).join(' ')];
}

/**
 * Maps one raw tasting note (e.g. "Jammy Blackberry", "cocoa nibs", "Rainier cherry & rose")
 * to flavor family ids. Longest phrases win; each word is used at most once. Returns [] when nothing matches.
 */
export function mapTastingNote(raw: string): FlavorFamilyId[] {
  const words = normalizeText(raw).split(' ').filter(Boolean);
  const used: boolean[] = new Array<boolean>(words.length).fill(false);
  const found: FlavorFamilyId[] = [];
  for (let n = Math.min(MAX_NGRAM, words.length); n >= 1; n--) {
    for (let i = 0; i + n <= words.length; i++) {
      if (used.slice(i, i + n).some(Boolean)) continue;
      const id = lookup(words.slice(i, i + n).join(' '));
      if (id) {
        for (let k = i; k < i + n; k++) used[k] = true;
        if (!found.includes(id)) found.push(id);
      }
    }
  }
  return found;
}

/** Maps a list of raw notes; returns unique ids plus the notes that matched nothing. */
export function mapTastingNotes(notes: readonly string[]): {
  families: FlavorFamilyId[];
  unmapped: string[];
} {
  const families: FlavorFamilyId[] = [];
  const unmapped: string[] = [];
  for (const note of notes) {
    const ids = mapTastingNote(note);
    if (ids.length === 0) unmapped.push(note);
    for (const id of ids) if (!families.includes(id)) families.push(id);
  }
  return { families, unmapped };
}
